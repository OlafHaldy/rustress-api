// Функция для расстановки ударений в тексте
function markStress(text) {
    let result = text;
    // Сортируем слова по длине (чтобы сначала обрабатывать более длинные)
    const sortedWords = Object.keys(stressDict).sort((a, b) => b.length - a.length);
    
    for (const word of sortedWords) {
        // Используем регулярное выражение для замены слов (независимо от регистра)
        const regex = new RegExp(`\\b(${word})\\b`, 'gi');
        result = result.replace(regex, stressDict[word]);
    }
    return result;
}

// Эндпоинт для расстановки ударений
app.post('/stress', (req, res) => {
    const { text } = req.body;
    
    if (!text || typeof text !== 'string') {
        return res.status(400).json({ error: 'Текст не предоставлен или не является строкой' });
    }

    try {
        const result = markStress(text);
        res.json({ result });
    } catch (error) {
        console.error('Ошибка при обработке:', error);
        res.status(500).json({ error: error.message });
    }
});

